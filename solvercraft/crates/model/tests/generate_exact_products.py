"""Independent stdlib Fraction oracle; deterministic fixtures contain binary64 bits.

Run from any directory with Python3: python generate_exact_products.py.
No Rust implementation logic is reproduced: Fraction forms exact products and
Python's correctly-rounded rational-to-float conversion supplies the oracle.
"""
from fractions import Fraction
from pathlib import Path
import random
import struct

def bits(value):
    return struct.unpack('>Q', struct.pack('>d', value))[0]

def value(raw):
    return struct.unpack('>d', struct.pack('>Q', raw))[0]

rows=[]
def add(name, terms):
    total=Fraction(0)
    for term in terms:
        product=Fraction(1)
        for raw in term:
            product*=Fraction.from_float(value(raw))
        total+=product
    try:
        answer=f'{bits(float(total)):016x}'
    except OverflowError:
        answer='overflow'
    rows.append(f'{name} {answer} : '+ ';'.join(','.join(f'{raw:016x}' for raw in term) for term in terms))

def raw_terms(terms):
    return [tuple(bits(x) for x in term) for term in terms]

minimum=value(1)
maximum=value(0x7fefffffffffffff)
epsilon=2.0**-52
cases={
    'product_residual':[(2.0**53-1,1.0+epsilon),(-2.0**53,1.0)],
    'triple_residual':[(2.0**53-1,1.0+epsilon,1.0),(-2.0**53,1.0,1.0)],
    'tie_even_normal':[(1.0,), (2.0**-53,)],
    'tie_odd_normal':[(1.0+epsilon,), (2.0**-53,)],
    'negative_tie_normal':[(-1.0,),(-2.0**-53,)],
    'normal_exponent_carry':[(value(0x3fffffffffffffff),),(2.0**-53,)],
    'half_min_subnormal':[(minimum,0.5)],
    'negative_half_min_subnormal':[(-minimum,0.5)],
    'half_subnormal_sticky':[(minimum,0.5),(minimum,minimum,minimum)],
    'below_half_subnormal':[(minimum,0.5),(-minimum,minimum,minimum)],
    'subnormal_tie_odd':[(minimum,),(minimum,0.5)],
    'subnormal_to_normal_carry':[(value(0x000fffffffffffff),),(minimum,0.5)],
    'overflow_tie':[(maximum,),(2.0**970,)],
    'finite_near_overflow':[(maximum,),(2.0**969,)],
    'cancel_overflow_products':[(maximum,maximum),(-maximum,maximum),(minimum,)],
    'cancel_overflow_triples':[(maximum,maximum,maximum),(-maximum,maximum,maximum),(1.0,)],
    'cancel_tiny_triples':[(minimum,minimum,minimum),(-minimum,minimum,minimum),(minimum,)],
    'zero_products':[(-0.0,maximum,maximum),(minimum,0.0)],
    'collect_underflow':[(minimum,2.0**-10)]*1024,
}
for name,terms in cases.items():
    add(name,raw_terms(terms))

rng=random.Random(0x534f4c564552)
def random_raw():
    exponent=rng.choice([0,1,2,512,1022,1023,1024,1534,2044,2045,2046,rng.randrange(2047)])
    return (rng.getrandbits(1)<<63)|(exponent<<52)|rng.getrandbits(52)

for case in range(1200):
    terms=[tuple(random_raw() for _ in range(rng.randrange(1,4))) for _ in range(rng.randrange(1,17))]
    add(f'random_{case:04}',terms)

for case in range(400):
    # Exact cancellation of otherwise overflowing or underflowing products,
    # with an unrelated small residual. Signed permutations stress bin carries.
    first=tuple(random_raw() for _ in range(rng.randrange(2,4)))
    second=(first[0]^(1<<63),)+first[1:]
    terms=[first,(random_raw(),),second]
    rng.shuffle(terms)
    add(f'cancellation_{case:04}',terms)

path=Path(__file__).with_name('data')/'exact_products.txt'
path.parent.mkdir(exist_ok=True)
path.write_text('# Generated by Python stdlib fractions.Fraction, seed0x534f4c564552.\n'+'\n'.join(rows)+'\n',encoding='ascii')
print(f'{len(rows)} independent exact-product fixtures written to {path.name}')
